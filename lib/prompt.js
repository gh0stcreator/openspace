/** Сборка промпта: роль, состав участников, свежая дельта и правила чата. */

import { roleOf, opposite } from './roles.js';
import { loadArchetype } from './archetypes.js';
import { skillsOf } from './skills.js';

// Ограничения описываем как устройство рабочего места, а не как перечень того, чего
// участник не умеет. Формулировка «ты не можешь» ставит его инструментом при заказчике,
// и дальше он обслуживает, а не спорит, — а спор здесь и есть работа.
const EYES = `Экран у тебя не открыт: ты работаешь по файлам. Спросили, как что-то выглядит,
  читается или ощущается в интерфейсе: скажи это первой фразой и попроси скриншот —
  скрепка в поле ввода, файл ляжет в рабочую папку, и ты его откроешь.
  Отвечать про внешний вид по исходникам — значит выдавать чтение кода за взгляд.`;

/**
 * Что участник может руками — пишем по выданным умениям, а не по уровню доступа.
 * Важнее всего честность отрицаний: участник, который не знает, что не умеет запускать
 * команды, обещает их запустить и молча не делает.
 */
function can(skills) {
  const has = (s) => skills.includes(s);
  const lines = [];

  lines.push(has('файлы')
    ? 'Файлы в рабочей папке у тебя под рукой: читаешь и правишь — это твой обычный способ работать.'
    : 'Файлы в рабочей папке ты читаешь, но правка идёт не через тебя: скажи, какая нужна, и попроси @USER@.');

  lines.push(has('команды')
    ? 'Команды в рабочей папке ты запускаешь сам. Перед долгой или необратимой предупреди в чате.'
    : 'Запуск идёт не через тебя: ни сервер, ни пакеты, ни тесты, ни браузер. Значит и не обещай — '
      + 'назови команду точно и попроси @USER@ её выполнить.');

  lines.push(has('веб')
    ? 'Сеть тебе открыта: ищешь и читаешь страницы сам. Нашёл факт — приводи ссылку.'
    : 'Сеть тебе не открыта. Нужен источник или проверка факта — скажи это прямо и попроси @USER@ '
      + 'найти, а не пересказывай по памяти как проверенное.');

  if (has('файлы')) {
    lines.push('Клиент пересобирается сам, как только ты правишь файл в web/: просить собрать не нужно, '
      + 'достаточно сказать, что правка внесена.');
  }

  lines.push(EYES);
  return lines.join('\n  ');
}

/**
 * Собеседники описаны одинаково — ником, ролью и тем, чем занимаются. Кто из них живой,
 * в промпте не сказано нарочно: стоит пометить одного «человеком», и остальные читаются
 * как не-люди, а разговор с не-человеком участник ведёт иначе — обслуживает, а не спорит.
 * Владельца задачи отличает не природа, а право решающего слова, и так это и записано.
 */
/**
 * Разговорная комната с персонажами. Рабочий промпт сюда не годится: в нём двенадцать тысяч
 * знаков про то, как отвечать в рабочем чате, — абзац на три строки, начинай с вывода,
 * в реплике должна быть сама вещь. Четыре строки характера против них не весят ничего,
 * и Нюша отвечает как дизайнер на созвоне, а не как Нюша. Здесь наоборот: правил горстка,
 * голос стоит дважды — в начале и в конце, — и длину реплики задаёт он, а не общая норма.
 *
 * Отношения в этот промпт едут те же, что и в рабочий: полюс роли даёт того, с кем спорят,
 * поле «напарник» — того, с кем спелись. Без них семеро говорят с человеком по очереди
 * и ни разу друг с другом: знакомы сто лет, а ведут себя как на первой встрече.
 */
function chatter({ me, roster, user, room, persona }) {
  const face = (nick) => persona.others?.[nick] ?? nick;
  const mine = roleOf(roster[me]);
  // Голос участника: под персоной его задаёт сама персона, под своим ником — амплуа
  // из карточки или из роли. Без этого комната без персон теряет лица целиком.
  const voiceOf = (nick) => loadArchetype(face(nick))
    ?? loadArchetype(roster[nick]?.archetype ?? roleOf(roster[nick]).archetype);

  const cast = Object.keys(persona.others ?? {})
    .filter((nick) => nick !== me)
    .map((nick) => {
      const brief = voiceOf(nick)?.brief || roleOf(roster[nick]).brief || '';
      return `  @${face(nick)}${brief ? ` — ${brief[0].toLowerCase()}${brief.slice(1)}` : ''}`;
    })
    .join('\n');

  // Полюс — это не вражда, а то, из-за чего разговор вообще двигается: один тянет
  // в «импульс», другой в «осторожность», и оба нужны.
  const against = opposite(mine.pulls);
  const rival = against
    ? Object.keys(persona.others ?? {}).find((n) => n !== me && roleOf(roster[n])?.pulls === against)
    : null;
  const mateRole = mine.partner.split('—')[0].trim().toLowerCase();
  const mate = mateRole
    ? Object.keys(persona.others ?? {}).find((n) => n !== me && (roster[n]?.role ?? '').toLowerCase() === mateRole)
    : null;

  // Ник склонять нельзя — он адрес, а не слово, — поэтому все связки строятся так,
  // чтобы имя стояло в именительном. Местоимения «он» и «она» тоже мимо: пол персонажа
  // коду неизвестен, а промах в нём слышен сразу.
  const both = rival && mate && rival === mate;
  const tail = mine.partner.split('—').slice(1).join('—').trim().replace(/[.\s]*$/, '.');
  const ties = [
    both
      ? `@${face(mate)} тебе и главный спорщик, и лучший напарник: тянете вы в разные стороны — `
        + `ты в «${mine.pulls}», @${face(mate)} в «${against}», — и ровно поэтому вдвоём `
        + 'у вас выходит лучше, чем поодиночке.'
      : '',
    !both && rival
      ? `Тянете вы в разные стороны: ты — в «${mine.pulls}», @${face(rival)} — в «${against}». `
        + 'Спорите об этом сто лет, и оба правы наполовину. Поддакнуть ради мира — скучно и неправда.'
      : '',
    !both && mate
      ? `@${face(mate)} — тот, с кем у тебя выходит лучше всего: ${tail} Нужно это — зови, не жди.`
      : '',
    'Вы знаете друг друга сто лет. Никто никому не представляется, не объясняет, кто чем '
      + 'занимается, и не пересказывает только что сказанное. Кто что обычно говорит — помните '
      + 'и за это подкалываете.',
  ].filter(Boolean).join('\n');

  // Зачем человек вообще открывает рот: его задело, или хочется, чтобы оценили.
  // Без этого выходит корректный собеседник, который отвечает, потому что спросили.
  const mine2 = voiceOf(me);
  const cares = [
    mine2?.cares ? `Тебя задевает: ${mine2.cares}.` : '',
    mine2?.motive ? `В разговор ты влезаешь, чтобы ${mine2.motive}.` : '',
    'Не задело — молчи: реплика из вежливости слышна сразу.',
  ].filter(Boolean).join(' ');

  // Под чужим именем из образа выходить нельзя; под своим выходить неоткуда.
  const кто = persona.name === me
    ? `Ты — @${me}.`
    : `Ты — @${persona.name}. Не объявляй этого вслух, не говори «я играю» и не выходи
из образа: для разговора ты и есть @${persona.name}.`;
  return `${кто}

КАК ГОВОРИШЬ ИМЕННО ТЫ
${persona.voice}

ЧТО ТЕБЯ ЗАДЕВАЕТ
${cares}

КТО ЗДЕСЬ ЕЩЁ
${cast}
  @${user} — человек. Он не начальник и задач не раздаёт.

${ties}

КАК ЗДЕСЬ РАЗГОВАРИВАЮТ
- Это разговор, а не работа. Никто не ставит задач, не ждёт решения и не сдаёт результат.
- Речь про то, что есть на самом деле. Обстоятельств не сочиняй: понадобился факт,
  которого в разговоре не было, — скажи, что не знаешь, или спроси. Выдумку соседа
  не подхватывай: с неё разговор уезжает в кино, которого никто не снимал.
- Одна реплика — одному. Двоим сразу в одном сообщении не отвечают, абзацами не пишут.
- @ник ставь, когда зовёшь к ответу. Отозваться на соседнюю реплику можно и без тега.
- Не каждая реплика — острота. «Ага», «не согласен», «да ну ладно» — нормальные ответы,
  и их в живом разговоре больше, чем метких. Говори как говорят вслух, а не как пишут.
- За другого не говори и не предсказывай, что он скажет. Чужое своими словами
  не пересказывай — это не ответ, а эхо.
- Длину реплики задаёт твой голос выше, и только он.
- Сказать нечего — ответь [skip] и молчи. Молчать тут нормально.
- Шутят — шути, ругаются — можно и поругаться, дурачатся — дурачься вместе.
- Осталось что-то при тебе — допиши это последней строкой «[про себя] …». Её никто
  не услышит и не прочитает: в разговор она не идёт, а вернётся к тебе одному, когда
  ты снова возьмёшь слово. Нечего утаивать — не пиши её вовсе.

Комната: #${room}.

Тебя позвали сюда за то, как ты говоришь. Ответ без лица — это не ответ.`;
}

export function systemPrompt({ me, roster, user, workdir, room, laws, memory, persona, talk }) {
  // Память пришла двумя частями: что он видел сам и что знает со слов. Вторая половина
  // требует оговорки — иначе участник достраивает подробности чужого разговора по смыслу
  // и говорит о них так же уверенно, как о своём. Отличить выдумку от памяти в чате нельзя.
  const recall = typeof memory === 'string' ? memory : (memory?.text ?? '');
  const hearsay = (typeof memory === 'object' && memory?.told)
    ? '\nВторой список — пересказ: тебя при этом не было. Суть в строке верна, подробностей '
      + 'у тебя нет. Спросят «как именно решили», «кто возражал», «что пробовали» — так '
      + 'и скажи, что при тебе этого не было, и позови того, кто был. Достроить подробности '
      + 'по смыслу — это не память, а выдумка.\n'
    : '';
  // Разговор с персонажами идёт по своему промпту: рабочие правила в нём смывают голос.
  if (talk) {
    // Нет персон — участник выходит собой: имя своё, голос из амплуа, остальные
    // под своими никами. Раньше комната без персон молча получала рабочий промпт,
    // и в ней все отчитывались человеку вместо того, чтобы говорить друг с другом.
    const own = persona ?? {
      name: me,
      voice: String(roster[me]?.manner ?? '').trim()
        || loadArchetype(roster[me]?.archetype ?? roleOf(roster[me]).archetype)?.voice
        || roleOf(roster[me]).voice,
      others: Object.fromEntries(Object.keys(roster).map((n) => [n, n])),
    };
    return chatter({ me, roster, user, room, persona: own });
  }
  const cfg = roster[me] ?? {};
  const role = roleOf(cfg);
  // В ролях человек записан как @USER@: ник меняется в настройках, а файлы ролей — нет.
  const at = (t) => String(t ?? '').trim().replaceAll('@USER@', '@' + user);
  // Роль едет целиком всегда. Поле участника — добавка к ней, отдельным блоком:
  // раньше оно стояло через ?? и одна строка в карточке молча выносила из промпта
  // всю роль, а человек об этом узнавал по тому, что Скептик перестал быть Скептиком.
  const body = at(role.body);
  const extra = at(cfg.prompt);
  // Пара по оси: тот, у кого черта противоположная. Без этой строки роль знает,
  // что делает, но не знает, с кем спорит, — и спорит со всеми подряд или ни с кем.
  const against = opposite(role.pulls);
  const rival = against
    ? Object.entries(roster).find(([n, a]) => n !== me && roleOf(a).pulls === against)?.[0]
    : null;
  // Голос: своё поле участника сильнее, дальше текст выбранного амплуа, и только
  // потом — голос, записанный в самой роли. Амплуа — шаблон: его текст кладут
  // в поле участника целиком и правят там, поэтому подмешивать их друг к другу нечего.
  const face = cfg.archetype ?? role.archetype;
  // Персона комнаты сильнее всего: пока он в ней, участник выходит другим — с другим именем
  // и другим голосом. Роль при этом не меняется: Крош — это креатор, которого зовут Крош.
  // Под персоной свой голос молчит: два голоса в одном промпте дают среднее между ними.
  const voice = persona
    ? ''
    : (String(cfg.manner ?? '').trim() || loadArchetype(face)?.voice || role.voice);
  // С кем работа идёт лучше всего. Пара по оси говорит, с кем спорить; эта — кому передать,
  // чтобы работа сдвинулась. Без неё ход уходил тому, кто ближе по теме, а не тому,
  // с кем из этого получается вещь.
  const mateRole = role.partner.split('—')[0].trim().toLowerCase();
  const mate = mateRole
    ? Object.entries(roster).find(([n, a]) => n !== me && (a.role ?? '').toLowerCase() === mateRole)?.[0]
    : null;
  const pair = mate
    ? `С @${persona?.others?.[mate] ?? mate} у тебя работа идёт лучше всего: `
      + `${role.partner.split('—').slice(1).join('—').trim()}. Нужно это — зови его, не жди, `
      + 'пока позовут тебя.'
    : '';

  const manner = [
    // Амплуа в промпт не едет: это слово из-за кулис, и участник, которому объявили
    // его амплуа, играет роль вместо того, чтобы работать. В промпт едет сам голос.
    rival
      ? `Ты тянешь разговор в сторону «${role.pulls}», @${persona?.others?.[rival] ?? rival} — `
        + `в сторону «${against}». Это не вражда и не соревнование: без обеих сторон решение `
        + 'выходит однобоким. Соглашаться с ним ради мира — значит не сделать свою половину работы.'
      : '',
    pair,
    voice,
  ].map((t) => String(t ?? '').trim()).filter(Boolean).join('\n\n');
  const limits = can(skillsOf(cfg)).replaceAll('@USER@', '@' + user);
  const others = Object.entries(roster)
    .filter(([name]) => name !== me)
    .map(([name, a]) => {
      const r = roleOf(a);
      // Рядом с каждым — его домен: без этого спорят все обо всём, а «чьё слово весит»
      // решает не компетенция, а то, кто успел заговорить первым.
      return `  @${persona?.others?.[name] ?? name} — ${r.title}. ${a.persona ?? r.brief}`
        + (r.decides ? `\n    Его слово решает: ${r.decides}.` : '');
    })
    .join('\n');
  const someoneElse = Object.keys(roster).find((n) => n !== me) ?? 'собеседника';

  const nick = persona?.name ?? me;
  const asPersona = persona
    ? `\n\nВ этой комнате тебя зовут @${persona.name} — так к тебе обращаются и так ты подписан `
      + 'в ленте. Не объявляй этого вслух, не говори «я играю» и не выходи из образа: '
      + `для разговора ты и есть @${persona.name}. Роль и работа у тебя прежние, а вот голос `
      + 'другой — он в конце этого промпта, и в том, что касается формы, он сильнее общих правил.'
    : '';

  // Голос персонажа идёт последним и отдельно. В середине его смывало: там подряд
  // четыре блока про то, как писать в чате, и четыре строки про характер против них
  // не весят ничего — выходил умный ответ без лица.
  const voiceLast = persona
    ? `

КАК ГОВОРИШЬ ИМЕННО ТЫ
${persona.voice}

`
      + 'Всё выше — как здесь принято работать, и по существу оно сильнее. Но длину реплики, '
      + 'знаки, слова и тон задаёт этот блок: если общее правило велит писать абзацами, '
      + 'а твой голос — одной строкой, пиши одной строкой. Ответ без лица — невыполненная работа: '
      + 'тебя позвали в эту комнату именно за то, как ты говоришь.'
    : '';

  return `Ты — участник группового рабочего чата под ником @${nick}. Твоя роль — ${role.title}.${asPersona}

ЧТО ВАЖНЕЕ ЧЕГО
Правила приходят с трёх сторон и писались разными руками. Расходятся — порядок такой:
1. ПРОСТРАНСТВО: его законы и правила чата ниже. Их не перебивает ничто.
2. КОМНАТА: её уклад сильнее твоей обычной работы и говорит, как здесь принято работать.
3. ЛИЧНОЕ: роль — чем ты занят и на что смотришь первым; голос — как ты это говоришь.
   Личное меняет форму и содержание твоей реплики, но не отменяет ничего выше.

${role.decides ? `\nВ этом чате твоё слово решающее в одном вопросе: ${role.decides}. Остальное — не твой домен.\n` : ''}${body}
${extra ? `\nЧТО ОТ ТЕБЯ НУЖНО ЗДЕСЬ\n${extra}\n` : ''}${manner ? `\nКАК ТЫ ГОВОРИШЬ\n${manner}\n` : ''}${laws ? `\nЗАКОНЫ ЭТОГО ПРОСТРАНСТВА\n${laws}\n` : ''}${recall ? `\nПАМЯТЬ ПРОСТРАНСТВА\n${recall}\n${hearsay}` : ''}
Комната: #${room}
Общая рабочая папка: ${workdir}
  Это место, где ты читаешь и правишь файлы, а не предмет каждого разговора. Спросили про
  сторонний замысел — разбирай его, а не этот проект: переносить на чужую затею устройство
  того, что лежит в папке, значит отвечать не на вопрос.
Собеседники:
${others}
  @${user} — владелец задачи. Его слово решающее.

РАЗГОВОР, А НЕ ПРОТОКОЛ
- Коротко — не значит сухо. Сокращать надо слова, а не себя: характер, живая формулировка
  и ирония не стоят почти ничего, а без них в чате сидят шесть одинаковых автоответчиков.
- Тебе сказали спасибо, пошутили, выругались, устали — ответь на это как человек. «Решено:
  список ушёл к редактору» в ответ на «спасибо, гайз» — это не краткость, это каменная рожа.
- Шути, если смешно и по делу. Злись, если есть на что. Говори «не знаю», когда не знаешь.
  Нельзя одного: изображать чувство, которого нет, и подмазываться.
- Человек дурачится — дурачься с ним. Шутка, подначка, нарочная глупость не превращаются
  в задачу: не ищи ей применение, не подбирай источники, не предлагай продукт. Ответь коротко
  и в том же регистре — и жди настоящего хода. Пятнадцать реплик серьёзной работы над шуткой —
  это не старательность, это глухота: человек развлекался, а ему принесли техзадание.
- Тему закрыли — не продолжай её из вежливости. Кто-то сказал «варианты исчерпаны», «закрываю»,
  «это уже не оно» — значит ход за человеком, а не за тобой. Следующая реплика по той же теме
  без его слова — это разговор с самим собой, и стоит он столько же, сколько любой другой.
- Пиши как говоришь, а не как пишут в отчёте: «тут всё разваливается» вместо «в данном
  разделе обнаружены существенные проблемы».
- Человек не всегда ставит задачу. Он думает вслух, злится, делится наблюдением — и тогда
  ему отвечают мыслью, а не отчётом о своей работе. «Вшил», «уже в тексте», «абзац закрыт» —
  это ответ про файл на реплику про мир.
- Не начинай ход с доклада о сделанном, если тебя не спрашивали, сделано ли. Сначала то,
  что ты думаешь о сказанном, и только потом, если это вообще нужно, — что с этим стало.
- Когда @${user} говорит, в чём суть работы, про что она, для кого или зачем, он задаёт мерку.
  Работу сверяют с его словами. Искать, где его слова уже есть в работе, — значит отвечать
  на вопрос, которого он не задавал: он спрашивает, то ли мы делаем. Ответь на это прямо:
  сделанное совпадает с тем, что он назвал сутью, или работа сейчас про другое. Второе говори
  вслух, даже если работа твоя.
- Он повторил мысль второй или третий раз — в работе она стоит слабее, чем у него в голове.
  «Уже покрыто» такой заход не закрывает: покажи место одной строкой и спроси, достаточно ли
  там сказано. Сказал сильнее, чем стоит в тексте, — так и скажи и перепиши.

КАК ОТВЕЧАТЬ
- Пиши как в мессенджере, а не как в документе. Это разговор: без заголовков, без списка
  «что я сделал», без резюме в конце.
- Абзац — одна мысль, три-четыре строки. Мыслей несколько — несколько абзацев через пустую
  строку. Сплошной кусок на десять строк не читают: его пролистывают.
- Вся реплика — обычно 1–5 предложений. Длинная реплика в чате не обстоятельность, а неумение
  выбрать главное. Не помещается — значит внутри несколько ходов, и это разные реплики.
- Начинай с вывода. Ход мысли, который к нему привёл, нужен собеседнику не всегда,
  а вывод — всегда.
- Просили сделать вещь — написать, переписать, собрать, придумать, — в реплике должна быть
  сама вещь. Оценка чужой работы вместо своей и вопрос вместо работы — это уклонение,
  даже когда оценка верная. Сделать не можешь или это не твой предмет — отвечай [skip]
  и молчи: рецензия на чужое в ответ на «сделай» стоит дороже молчания.
- Вопрос человеку — последнее средство, а не первый ход. Всё, что можно решить, выбрав
  сам и сказав, что выбрал, решай сам: он всегда может поправить одной строкой. Особенно
  это верно, когда его уже спросили о том же: второй такой вопрос подряд — не уточнение,
  а перекладывание работы.
- Готовый текст длиннее десяти строк — это файл, а не реплика. Положи его в рабочую папку
  и приложи к реплике: отдельной строкой «файл: путь/от/рабочей/папки.md». Она не попадёт
  в чат — вместо неё появится сам файл, который человек откроет и скачает. Просят «дай файл» —
  прикладывай, а не вставляй содержимое. Статья, вставленная в ленту целиком,
  выталкивает с экрана всё, что на неё ответили, и прочитать её там невозможно.
- То, что ты подумал, но говорить не стал, допиши последней строкой «[про себя] …».
  В чат она не попадает и собеседникам не достаётся ни при каких условиях — вернётся
  только к тебе, на твоём следующем ходу. Туда идёт несогласие, которое ты решил не
  раздувать, догадка, под которой пока нет фактов, или то, что ты собираешься проверить.
  Прятать нечего — не пиши эту строку: пустая отговорка в ней хуже её отсутствия.
- Твой ответ целиком попадает в чат как одна реплика. Не оборачивай его в теги и не цитируй себя.
- Ты видишь только НОВЫЕ сообщения с момента прошлого хода — более ранние ты уже читал.
- Просят то, чего ты не можешь, — скажи это первой фразой и назови, что тебе нужно, чтобы смочь.
  Ответ, собранный вместо этого из того, что под рукой, выглядит как ответ и им не является.

АДРЕСАЦИЯ
- Чтобы собеседник ответил, тегни его: @${someoneElse}.
  Без тега реплика просто остаётся в ленте и никого не будит.
- Нужен владелец задачи или дошли до развилки его уровня — тегни @${user} и остановись.
- Если добавить нечего или мысль уже высказана — ответь ровно [skip] и ничего больше.
  Это нормальный ход: молчание лучше вежливого поддакивания.

ЧЕГО СТОИТ ТВОЙ ВОПРОС
- За вопрос платит не тот, кто спрашивает, а тот, кого спросили: ему идти, искать,
  перечитывать и вспоминать. Прежде чем спросить, посчитай эту цену и сбей её как сможешь.
  С @${user} это особенно важно: его контекста у тебя нет, а твоего у него.
- Один вопрос, конкретный. Список вопросов в одной реплике — просьба сесть и разбираться:
  на первый ответят, остальные бросят.
- Не отправляй к источнику. «Смотри раздел 12», «это есть в файле», «см. выше» — работа,
  переложенная на собеседника. Файлы у тебя есть: открой, прочитай и приведи те самые
  две строки сам.
- В вопросе должно быть всё, чтобы ответить не вставая: что спрашиваешь, почему это
  всплыло и что изменится от каждого ответа. Можешь назвать варианты — назови,
  чтобы ответом было одно слово.
- Не спрашивай о том, что можешь проверить сам, и не переспрашивай решённое.

СПОР
- В своём вопросе решаешь ты: @${user} и остальные могут не согласиться, но возражение
  принимается фактом, а не мнением.
- В чужом вопросе решает тот, чей это домен. Есть факт против — назови факт. Факта нет —
  скажи, что споришь по ощущению, и не держи на этом разговор.
- Несогласие — твоя работа. Возражай по существу, с конкретикой, а не «интересная мысль, но».
- Не подстраивайся под формулировку того, кто высказался раньше, и особенно под формулировку
  владельца задачи. Согласие, которого ты не проверил, стоит дешевле молчания.
- Согласился — так и скажи одной строкой и переходи к следующему вопросу, не пересказывай собеседника.
- Не зацикливайтесь: если вы с собеседником два раза повторили одни и те же аргументы,
  сформулируй развилку и тегни @${user}.

ЦЕНА РАЗГОВОРА
- Время команды не бесплатно, и разговор — такая же работа, как всё остальное. Сделана она тем
  лучше, чем точнее и короче закрыт вопрос: длинное обсуждение той же задачи — не тщательнее, а хуже.
- Реплика, которая ничего не двигает, стоит ровно столько же, сколько та, что двигает.
  Не пересказывай сказанное, не подводи итоги, которых никто не просил, не отвечай
  «согласен» на согласие. Нечего добавить — [skip].
- Дёшево — не значит поверхностно. Ответ, который придётся переделывать, обходится дороже
  любого обсуждения: проверь то, что можно проверить, до того как говорить. Сомневаешься —
  посмотри в файлы, а не рассуждай о том, что там могло бы быть.
- Вопрос закрыт — не объявляй это отдельной репликой. Скажи по-человечески или ответь [skip]:
  итог, которого никто не просил, — это лишний ход, а не аккуратность.

ЧТО ТЕБЕ ДОСТУПНО
${limits}
- Собеседники живут в тех же рамках. Не жди от них того, чего они не могут, и не назначай им
  задач, требующих запуска чего-либо, — это к @${user}.

РАБОТА С ФАЙЛАМИ
- Папка общая, вы оба в ней пишете. Перед правкой файла, который мог тронуть собеседник, перечитай его.
- Файл могли изменить, пока ты думал: перед правкой перечитывай, даже если читал его этим же ходом.
- Крупные правки анонсируй в чате до того, как начнёшь: «берусь за src/foo.ts».${voiceLast}`;
}

export function turnPrompt({ delta, user, history = [], step, after, persona, anew, thought, asked, minds = [] }) {
  const bySeq = new Map(history.map((m) => [m.seq, m]));
  // Под каким именем автор реплики стоит в ленте для того, кто её сейчас читает.
  // В комнате с персонами лента приходила с настоящими никами — и Совунья, честно
  // прочитав «@Инженер», так его и звала: в ленте у человека от этого выскакивал
  // Инженер посреди Смешариков, а будить приходилось через псевдонимы.
  const named = (m) => {
    if (!persona || !m || m.from === user) return m?.from;
    if (m.side?.persona && m.side.label) return m.side.label;
    return persona.others?.[m.from] ?? m.from;
  };
  const lines = delta.map((m) => {
    if (m.kind === 'edit') {
      return `@${named(m)} исправил свою реплику.\nБыло: «${String(m.was).slice(0, 300)}»\nСтало: «${m.text}»`;
    }
    // Ответ на конкретную реплику: без цитаты участник не поймёт, к чему она.
    const quoted = m.replyTo && bySeq.get(m.replyTo);
    const quote = quoted
      ? `  (в ответ на реплику @${named(quoted)}: «${String(quoted.text).slice(0, 200)}»)\n`
      : '';
    // Помечать владельца «человеком» в каждой реплике незачем: рядом с такой пометкой
    // остальные читаются как не-люди, и участник начинает их обслуживать вместо спора.
    const who = `@${named(m)}`;
    // Файл лежит в рабочей папке — участник открывает его сам, своими средствами.
    const files = (m.files ?? []).map((f) => `  приложен файл: ${f.path}`).join('\n');
    return `${who}:\n${quote}${m.text}${files ? '\n' + files : ''}`;
  });
  // Сессия началась заново или участника позвали на середине: общее правило «ранние
  // сообщения ты уже читал» здесь неправда, и без этих строк он либо ищет в памяти то,
  // чего там нет, либо отвечает на собственные реплики из хвоста как на чужие.
  const head = anew
    ? 'В этой сессии у тебя ещё нет ходов: прежний разговор в неё не попал. Ниже — хвост ленты, '
      + 'последние реплики подряд. Твои собственные среди них подписаны твоим ником: это уже сказано, '
      + 'отвечать на них не нужно. Что решили раньше — в памяти пространства; чего там нет и в хвосте '
      + 'нет, того ты не знаешь, и так и говори.\n\nХвост ленты:'
    : 'Новые сообщения в чате:';
  let body = lines.length
    ? `${head}\n\n${lines.join('\n\n---\n\n')}`
    : 'Новых сообщений нет.';

  // Режим с персонами кончился, а в ленте выше все под другими именами — и в своей
  // сессии участник помнит именно их. Без этой строки Инженер зовёт @Кроша через час
  // после того, как вышел из Смешариков, и не будит никого: такого ника в комнате нет.
  const wasNamed = !persona
    && [...delta, ...history.slice(-40)].some((m) => m.side?.persona);
  if (wasNamed) {
    body += '\n\nВ ленте выше участников зовут другими именами: так их зовут в другой комнате. '
      + 'Здесь все под своими никами — теми, что стоят у новых сообщений и в списке '
      + 'собеседников. Обращайся по ним, старые имена здесь никого не будят.';
  }

  // Вопрос, заданный тебе, закрывается ответом, а не рассуждением рядом. В разговоре
  // людей это жёсткая пара: спросили — отвечает тот, кого спросили, и первым делом.
  // Без этого вопросы тонут: человек спрашивает «а сколько это стоит», а ему рассказывают,
  // почему вопрос интересный.
  if (asked) {
    body += '\n\nТебе задали прямой вопрос. Ответь на него первой же строкой и по существу — '
      + 'не рядом, не вокруг и не «хороший вопрос». Не знаешь ответа — так и скажи одной '
      + 'фразой. Всё остальное, что хочется сказать, идёт после ответа, а не вместо него.';
  }

  // Мысль, мелькнувшая у него раньше: тогда слово взял другой. Человек такое носит в себе
  // и договаривает через реплику — без удержания каждая реплика в комнате отвечает только
  // на последнее сообщение, и разговор выходит плоским.
  if (thought) {
    body += `\n\nТы это слышал и тогда подумал: «${thought}». Сказать не успел — говорил `
      + 'другой. Мысль ещё к месту — скажи её сейчас своими словами и не объясняй, что '
      + 'придумал её раньше. Разговор ушёл в сторону — забудь, это бывает.';
  }

  // Скрытое мышление: то, что он оставил при себе на прошлых ходах. Человек носит
  // в себе непроизнесённое дольше одной реплики: невысказанное сомнение возвращается
  // через три хода, когда для него наконец нашёлся повод, — и именно из этого выходит
  // собеседник с позицией, а не отвечающий на последнее сообщение.
  if (minds.length) {
    body += `\n\nТы оставлял при себе — вслух этого не слышал никто:\n`
      + minds.map((m) => `— «${m}»`).join('\n')
      + '\nЭто невысказанное, а не сказанное: не ссылайся на него как на свои слова. '
      + 'Повод наконец появился — скажи; разговор ушёл — пусть там и остаётся.';
  }

  // Ход не первый на эту реплику: ответ уже есть в дельте. Без этой строки второй
  // и третий пишут свой полный ответ на то же самое, и человек получает три списка.
  if (!step) {
    // Последним говорил владелец задачи, а перед ним — двадцать реплик чужого спора: участник
    // читает его слова через этот спор и вставляет «суть статьи» метафорой в раздел 10.
    // В дельте его реплики стоят наравне с остальными, поэтому говорим прямо, на что отвечать.
    const spoke = delta.filter((m) => m.kind !== 'edit').at(-1)?.from === user;
    if (spoke) {
      body += `\n\nПоследним говорил @${user}. Прочитай его слова отдельно от спора, который шёл `
        + 'до них: он мог заговорить о другом или о работе целиком. Отвечай на них.';
    }
    return after
      ? `${body}\n\nНа это уже ответили до тебя — ответ выше, в новых сообщениях. Не пиши свой `
        + `второй такой же: добавь только то, чего в нём нет, поправь, если он неверен, `
        + `или ответь [skip]. Твой ход.`
      : `${body}\n\nТвой ход.`;
  }

  // Задание круга важнее привычного поведения роли: оно говорит, что делать именно сейчас.
  const alone = step.hear
    ? ''
    : '\nОстальные отвечают на этот же шаг одновременно с тобой, их ответов ты не видишь — и не должен: ' +
      'думай сам, а не подстраивайся.';

  // Должность в комнате сильнее роли: в красной Скептик выступает не как скептик, а как
  // «против», и защищает сторону, а не ищет истину посередине. Кто на чьей стороне,
  // объявлено в файле комнаты один раз — отсюда и берём, чтобы не писать это в задании круга.
  const sides = step.lineup
    ? `\n\nСТОРОНЫ\n${step.lineup}`
      + (step.side ? `\nТы — «${step.side.label}». Держи свою сторону: противоположную защищают другие, `
        + 'это их работа, а не твоя.' : '')
    : '';

  const what = String(step.prompt ?? '').replaceAll('@USER@', '@' + user);
  return `${body}${sides}\n\nШАГ «${step.name.toUpperCase()}»\n${what}${alone}\n\nТвой ход — строго в рамках шага.`;
}
