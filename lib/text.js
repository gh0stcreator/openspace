/**
 * Развернуть жёсткие переносы внутри абзаца. Файлы ролей и амплуа свёрстаны по ширине
 * текста — так их читают в гите, — но то же самое поле человек правит в текстовой
 * области, где перенос ставит браузер. Два переноса подряд дают рваную лесенку.
 * Пустая строка остаётся разделителем абзацев: она значащая.
 */
export function unwrap(text) {
  return String(text ?? '')
    .split(/\n{2,}/)
    .map((p) => p.split('\n').map((l) => l.trim()).filter(Boolean).join(' '))
    .join('\n\n')
    .trim();
}
