/**
 * Типографика русского текста: короткие слова не должны висеть в конце строки.
 * Ставит неразрывные пробелы там, где перенос разрывает смысл.
 */

const NBSP = " "

// Любое слово из одной-двух русских букв — предлог, союз, частица или местоимение:
// «те же семеро» рвалось после «те», потому что список был поимённым и «те» в него
// не попало. Перечислять дальше бессмысленно — короткое слово висит в конце строки
// независимо от того, какая это часть речи.
const TINY = "[а-яё]{1,2}"

// Те, что длиннее двух букв, но спотыкаются так же.
const SHORT = "для|его|ее|её|или|как|над|под|при|про|так|что|чтоб|чтобы|уже|эти|это|этот|эта"

export function typo(input: string): string {
  if (!input) return input
  let s = input

  // Короткое слово прилипает к следующему. Дважды: в цепочке «и в том» первая замена
  // съедает пробел перед «в», и второму слову границы уже не хватает.
  const glue = new RegExp(`(^|[\\s(«"])(${TINY}|${SHORT})\\s+`, "gi")
  s = s.replace(glue, `$1$2${NBSP}`)
  s = s.replace(glue, `$1$2${NBSP}`)

  // Число не отрывается от того, что считает: «5 минут», «3 шага».
  s = s.replace(/(\d)\s+(?=[а-яё])/gi, `$1${NBSP}`)

  // Тире не начинает строку в одиночку — держим его при предыдущем слове.
  s = s.replace(/\s+([—–])\s+/g, `${NBSP}$1 `)

  // Инициалы и сокращения не разрываются: «и т. д.», «т. е.». Границу слова считаем
  // сами: `\b` в JS знает только латиницу, и для кириллицы это правило не срабатывало
  // никогда — та же грабля, на которой один раз уже молча умер маркер «заново».
  s = s.replace(/(^|[^а-яёa-z])([а-яё])\.\s+([а-яё])\./gi, `$1$2.${NBSP}$3.`)

  return s
}
