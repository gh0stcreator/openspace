/**
 * Типографика русского текста: короткие слова не должны висеть в конце строки.
 * Ставит неразрывные пробелы там, где перенос разрывает смысл.
 */

const NBSP = " "

// Предлоги, союзы и частицы, после которых перенос читается как спотыкание.
const SHORT =
  "а|в|во|да|для|до|его|ее|её|же|за|и|из|из-за|или|их|к|ко|как|ли|на|над|не|ни|но|о|об|обо|от|по|под|при|про|с|со|та|так|то|у|уж|что|чтоб|чтобы|бы|б|ж|же"

export function typo(input: string): string {
  if (!input) return input
  let s = input

  // Короткое слово прилипает к следующему.
  s = s.replace(new RegExp(`(^|[\\s(«"])(${SHORT})\\s+`, "gi"), `$1$2${NBSP}`)

  // Число не отрывается от того, что считает: «5 минут», «3 шага».
  s = s.replace(/(\d)\s+(?=[а-яё])/gi, `$1${NBSP}`)

  // Тире не начинает строку в одиночку — держим его при предыдущем слове.
  s = s.replace(/\s+([—–])\s+/g, `${NBSP}$1 `)

  // Инициалы и сокращения не разрываются: «и т. д.», «т. е.».
  s = s.replace(/\b([а-яё])\.\s+([а-яё])\./gi, `$1.${NBSP}$2.`)

  return s
}
